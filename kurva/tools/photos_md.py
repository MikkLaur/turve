 'Generated by `tools/photos_md.py` from `tools/crops.txt` and the last run (`work/<id>.json`). Sources are in',
 '`reklaamikampaania/.../kurvanokitseb.ee/previous-kurva-work/`. All processing is local; outputs are in `site/img/`',
