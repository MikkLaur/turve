import type { SiteConfig } from './config';

/** Security headers for the public site. Used in the generated .htaccess and by the dev server, so both match. */
export function securityHeaders(cfg: SiteConfig): Record<string, string> {
  return {
    'Content-Security-Policy': [
      "default-src 'none'",
      "script-src 'self'",
      "style-src 'self'",
      "img-src 'self'",
      "font-src 'self'",
      `connect-src ${cfg.apiOrigin}`,
      `form-action 'self' ${cfg.apiOrigin}`,
      "base-uri 'none'",
      "frame-ancestors 'none'",
      ...(cfg.dev ? [] : ['upgrade-insecure-requests']),
    ].join('; '),
    // includeSubDomains/preload only once every turve.ee subdomain is known to be HTTPS-only (see CLAUDE.md).
    'Strict-Transport-Security': 'max-age=31536000',
    'X-Content-Type-Options': 'nosniff',
    'X-Frame-Options': 'DENY',
    'Referrer-Policy': 'strict-origin-when-cross-origin',
    'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()',
    'Cross-Origin-Opener-Policy': 'same-origin',
    'Cross-Origin-Resource-Policy': 'same-origin',
  };
}

export function htaccess(cfg: SiteConfig): string {
  const host = new URL(cfg.siteOrigin).host.replace(/\./g, '\\.');
  const bare = host.replace(/^www\\\./, '');
  const headerLines = Object.entries(securityHeaders(cfg))
    .map(([name, value]) => `  Header always set ${name} "${value}"`)
    .join('\n');
  return `# Generated by site/src/build.ts – do not edit on the server.
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html
AddDefaultCharset utf-8
AddCharset utf-8 .html .css .js .txt .xml .svg
AddType text/plain .txt

RewriteEngine On
# One public address: http:// and bare ${bare.replace(/\\/g, '')} → ${cfg.siteOrigin}
RewriteCond %{REQUEST_URI} !^/\\.well-known/acme-challenge/
RewriteCond %{HTTPS} off [OR]
RewriteCond %{HTTP_HOST} ^${bare}$ [NC]
RewriteRule ^ ${cfg.siteOrigin}%{REQUEST_URI} [R=301,L]

<IfModule mod_headers.c>
${headerLines}
  <FilesMatch "\\.(html|xml|txt)$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
  <FilesMatch "\\.[0-9a-f]{10}\\.(css|js)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.(woff2|svg|webp|png|jpg)$">
    Header set Cache-Control "public, max-age=2592000"
  </FilesMatch>
</IfModule>
`;
}
