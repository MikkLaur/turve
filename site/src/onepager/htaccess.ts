/**
 * Apache config for a client's one-page site: one canonical HTTPS address and strict security headers, so the site
 * scores A on turve.ee's own check. The page has no scripts, fonts or forms, so the CSP allows only its own CSS and images.
 */
export function clientHtaccess(origin: string): string {
  let url: URL;
  try {
    url = new URL(origin);
  } catch {
    throw new Error(`--origin must be a URL like https://www.client.ee (got "${origin}")`);
  }
  if (url.protocol !== 'https:' || url.port || url.username || url.password || url.pathname !== '/' || url.search || url.hash) {
    throw new Error(`--origin must be just https:// and a host name, like https://www.client.ee (got "${origin}")`);
  }
  const canonical = `https://${url.host}`;
  const hostPattern = url.host.replace(/\./g, '\\.');
  const headers: Record<string, string> = {
    'Content-Security-Policy':
      "default-src 'none'; style-src 'self'; img-src 'self'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'; upgrade-insecure-requests",
    'Strict-Transport-Security': 'max-age=31536000',
    'X-Content-Type-Options': 'nosniff',
    'X-Frame-Options': 'DENY',
    'Referrer-Policy': 'strict-origin-when-cross-origin',
    'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()',
    'Cross-Origin-Opener-Policy': 'same-origin',
    'Cross-Origin-Resource-Policy': 'same-origin',
  };
  const headerLines = Object.entries(headers)
    .map(([name, value]) => `  Header always set ${name} "${value}"`)
    .join('\n');
  return `# Generated by the turve.ee one-pager kit (site/src/onepager/cli.ts) – rebuild instead of editing on the server.
Options -Indexes
DirectoryIndex index.html
AddDefaultCharset utf-8
AddCharset utf-8 .html .css .txt

RewriteEngine On
# One public address: http:// and any other host name → ${canonical}
RewriteCond %{REQUEST_URI} !^/\\.well-known/acme-challenge/
RewriteCond %{HTTPS} off [OR]
RewriteCond %{HTTP_HOST} !^${hostPattern}$ [NC]
RewriteRule ^ ${canonical}%{REQUEST_URI} [R=301,L]

<IfModule mod_headers.c>
${headerLines}
  <FilesMatch "\\.(html|txt)$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
  <FilesMatch "\\.(css|jpg|jpeg|png|webp)$">
    Header set Cache-Control "public, max-age=2592000"
  </FilesMatch>
</IfModule>
`;
}
