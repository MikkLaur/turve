    cut = c.get('cut', 'whole') + ' → ' + ','.join(map(str, j.get('crop_box', [])))
    fit = f"{j.get('theta_deg', 0):+.1f}, {j.get('v', 0):+.3f}"
    out.append(f"| `{id}` | {c['role']} | `{c['src']}`{' rot ' + c['rot'] if 'rot' in c else ''} | {cut} | {fit} | {lean}{flag} | {'2x Real-ESRGAN' if c.get('up') == '2' else 'no'} | {widths} |")
